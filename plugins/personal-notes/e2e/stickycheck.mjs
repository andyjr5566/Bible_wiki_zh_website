// 便條紙（12 N1）瀏覽器檢查。
// 用法：node e2e/stickycheck.mjs <siteRoot> <profile> [shotDir]
import { startBrowser, ch1, setVal, clickText, selectIn, toolbarButtons } from "./lib.mjs"

const [root, profile, shotDir] = process.argv.slice(2)
const s = await startBrowser({ root, profile, shotDir })
const { ev, check, go, send, shot, errors, setViewport, sleep, finish } = s

const vis = (sel) => `(() => { const e = document.querySelector(${JSON.stringify(sel)}); return !!e && getComputedStyle(e).display !== 'none' && e.getBoundingClientRect().height > 0 })()`
const cards = `[...document.querySelectorAll('li[data-v] .bwz-sticky')].map(c => ({ v: c.closest('li').dataset.v, color: c.dataset.color, text: (c.querySelector('.bwz-sticky-text')?.textContent ?? '').trim().slice(0, 40), editing: !!c.querySelector('textarea') }))`
const getCards = async () => JSON.parse(await ev(`JSON.stringify(${cards})`))
const typeIn = (sel, text) => `(() => { const t = document.querySelector(${JSON.stringify(sel)}); t.value = ${JSON.stringify(text)}; t.dispatchEvent(new Event('input', { bubbles: true })) })()`

await go(ch1 + "?skip=1")
// 1. 工具列有「便條」
await ev(selectIn(3, "要有光"))
await sleep(700)
const tb = await ev(toolbarButtons)
check("選取經文時工具列有「🗒 便條」", Array.isArray(tb) && tb.some((t) => t.includes("便條")), JSON.stringify(tb))
await ev(clickText(".bwz-h-toolbar button", "便條"))
await sleep(900)
const fresh = JSON.parse(await ev(`JSON.stringify((() => { const c = document.querySelector('li[data-v="3"] .bwz-sticky'); const t = c?.querySelector('textarea'); return { card: !!c, focused: !!t && document.activeElement === t, colors: c ? c.querySelectorAll('.bwz-sticky-color').length : 0 } })())`))
check("按「便條」後在第 3 節下方開一張空白便條、游標在輸入框", fresh.card && fresh.focused && fresh.colors === 4, JSON.stringify(fresh))
await ev(typeIn('li[data-v="3"] .bwz-sticky textarea', "記得對照約翰福音 1:5"))
await sleep(1200)
await ev(`document.querySelector('li[data-v="3"] .bwz-sticky .bwz-sticky-color[data-color="pink"]').click()`)
await sleep(800)
await ev(clickText('li[data-v="3"] .bwz-sticky button', "完成"))
await sleep(800)
let cs = await getCards()
check("打字自動儲存、換成粉紅色、按完成後顯示便條", cs.length === 1 && cs[0].v === "3" && cs[0].color === "pink" && cs[0].text.includes("約翰福音 1:5") && !cs[0].editing, JSON.stringify(cs))
check("經文文字不受便條影響", !(await ev(`(() => { const c = document.querySelector('li[data-v="3"]').cloneNode(true); c.querySelectorAll('.bwz-v-ui').forEach(e => e.remove()); return c.textContent.includes('約翰福音') })()`)))
await shot("s1-card")
// 2. 在便條上選字不會跳出畫重點工具列
await ev(`(() => { const t = document.querySelector('li[data-v="3"] .bwz-sticky .bwz-sticky-text'); const w = document.createTreeWalker(t, NodeFilter.SHOW_TEXT); const n = w.nextNode(); const r = document.createRange(); r.setStart(n, 0); r.setEnd(n, 2); getSelection().removeAllRanges(); getSelection().addRange(r) })()`)
await sleep(700)
check("在便條上選字不會跳出畫重點工具列", !(await ev(vis(".bwz-h-toolbar"))))
await ev(`getSelection().removeAllRanges()`)
// 3. 畫重點仍正常
await ev(selectIn(3, "要有光"))
await sleep(700)
await ev(clickText(".bwz-h-toolbar button", "畫重點"))
await sleep(1200)
check("有便條的經節照樣可以畫重點（只標選取的字）", (await ev(`[...document.querySelectorAll('li[data-v="3"] mark.bwz-hl')].map(m => m.textContent).join('')`)) === "要有光")
// 4. 本章全部收起／展開
const barText = await ev(`document.querySelector('.bwz-notes')?.textContent.match(/本章 ?\\d+ ?張便條/)?.[0] ?? null`)
const bar = await ev(`[...document.querySelectorAll('.bwz-notes button')].map(b => b.textContent.trim()).filter(t => t.includes('全部'))`)
check("面板顯示「本章 1 張便條」與「全部收起」", !!barText && barText.includes("1") && JSON.stringify(bar).includes("全部收起"), `${barText} ${JSON.stringify(bar)}`)
await ev(clickText(".bwz-notes button", "全部收起"))
await sleep(600)
check("全部收起：卡片不見、第 3 節最後出現 🗒", (await getCards()).length === 0 && (await ev(`!!document.querySelector('li[data-v="3"] .bwz-sticky-icon')`)))
await ev(`document.querySelector('li[data-v="3"] .bwz-sticky-icon').scrollIntoView({ block: 'center' })`)
await ev(`document.querySelector('li[data-v="3"] .bwz-sticky-icon').click()`)
await sleep(500)
cs = await getCards()
check("點小紙條：直接在第 3 節下方展開（不浮出視窗）", cs.length === 1 && cs[0].v === "3" && (await ev(`document.querySelectorAll('.bwz-sticky-pop').length`)) === 0, JSON.stringify(cs))
await shot("s2-expanded")
await ev(clickText(".bwz-notes button", "全部展開"))
await sleep(400)
// 5. 重新整理後還在
await send("Page.reload")
await sleep(4500)
cs = await getCards()
check("重新整理後便條還在（顏色、內容）", cs.length === 1 && cs[0].color === "pink" && cs[0].text.includes("約翰福音"), JSON.stringify(cs))
// 6. 刪除＋復原
await ev(`document.querySelector('li[data-v="3"] .bwz-sticky button[aria-label="刪除便條"]').click()`)
await sleep(800)
const toastText = await ev(`document.querySelector('.bwz-n-toast.show')?.textContent ?? null`)
check("刪除後便條消失、出現「復原」", (await getCards()).length === 0 && !!toastText && toastText.includes("復原"), toastText)
await ev(`document.querySelector('.bwz-n-toast .bwz-n-toast-action').click()`)
await sleep(1000)
cs = await getCards()
check("按「復原」便條回來（內容、顏色相同）", cs.length === 1 && cs[0].color === "pink" && cs[0].text.includes("約翰福音"), JSON.stringify(cs))
// 7. 空白新便條不留下；編輯中自動存
await ev(selectIn(5, "神稱光為晝"))
await sleep(700)
await ev(clickText(".bwz-h-toolbar button", "便條"))
await sleep(700)
await ev(clickText('li[data-v="5"] .bwz-sticky button', "完成"))
await sleep(700)
check("沒打字就按完成：不留下空白便條", (await ev(`document.querySelectorAll('li[data-v="5"] .bwz-sticky').length`)) === 0)
await ev(`document.querySelector('li[data-v="3"] .bwz-sticky button[aria-label="編輯便條"]').click()`)
await sleep(600)
await ev(typeIn('li[data-v="3"] .bwz-sticky textarea', "暫時的"))
await sleep(1200)
await send("Page.reload")
await sleep(4500)
check("編輯中打的字自動存好（重新整理後是新內容）", (await getCards())[0]?.text === "暫時的", JSON.stringify(await getCards()))
// 8. 換頁不殘留
await go("/" + encodeURI("01-創世記/第2章") + "?skip=1")
check("換到第 2 章不殘留第 1 章的便條", (await ev(`document.querySelectorAll('.bwz-sticky, .bwz-sticky-icon, .bwz-sticky-pop').length`)) === 0)
await go(ch1 + "?skip=1")
check("回到第 1 章便條只有一張", (await getCards()).length === 1)
// 9. 我的筆記頁的設定
await go("/my-notes")
const st = JSON.parse(await ev(`JSON.stringify((() => { const b = document.querySelector('.bwz-settings-btn'); const page = document.querySelector('[data-bwz-notes="mynotes"]'); return { btn: !!b, text: b?.textContent.trim(), first: !!b && !!page.firstElementChild?.contains(b) } })())`))
check("我的筆記頁最上方有「⚙ 設定」", st.btn && st.first && st.text.includes("設定"), JSON.stringify(st))
await ev(`document.querySelector('.bwz-settings-btn').click()`)
await sleep(500)
const radios = await ev(`[...document.querySelectorAll('.bwz-n-dialog input[type=radio]')].map(r => (r.closest('label')?.textContent.trim() ?? '') + (r.checked ? ' ✓' : ''))`)
check("設定視窗有兩個選項、預設是展開", Array.isArray(radios) && radios.length === 2 && radios[0].includes("展開") && radios[0].endsWith("✓"), JSON.stringify(radios))
await shot("s3-settings")
await ev(`document.querySelectorAll('.bwz-n-dialog input[type=radio]')[1].click()`)
await ev(clickText(".bwz-n-dialog button", "完成"))
await sleep(400)
await go(ch1 + "?skip=1")
check("設定成「收起」後，章節頁的便條是 🗒 小圖示", (await getCards()).length === 0 && (await ev(`!!document.querySelector('li[data-v="3"] .bwz-sticky-icon')`)))
await go("/my-notes")
await ev(`document.querySelector('.bwz-settings-btn').click()`)
await sleep(400)
await ev(`document.querySelectorAll('.bwz-n-dialog input[type=radio]')[0].click()`)
await ev(clickText(".bwz-n-dialog button", "完成"))
await sleep(300)
// 10. 手機版面
await setViewport(390, 844, { dpr: 2, mobile: true, touch: true })
await go(ch1 + "?skip=1")
await ev(`document.querySelector('li[data-v="3"] .bwz-sticky')?.scrollIntoView({ block: 'center' })`)
await sleep(400)
const mob = JSON.parse(await ev(`JSON.stringify((() => { const c = document.querySelector('li[data-v="3"] .bwz-sticky'); if (!c) return null; const r = c.getBoundingClientRect(); const btns = [...c.querySelectorAll('button')].map(b => Math.round(b.getBoundingClientRect().height)); return { left: Math.round(r.left), right: Math.round(r.right), vw: innerWidth, btns } })())`))
check("手機版：便條在畫面內、按鈕至少 44px", !!mob && mob.left >= 0 && mob.right <= mob.vw && mob.btns.length > 0 && mob.btns.every((x) => x >= 44), JSON.stringify(mob))
await shot("s4-mobile")
check("沒有 JavaScript 例外", errors.length === 0, errors.slice(0, 2).join(" | "))
finish()
