import { describe, expect, it } from 'vitest';
import readingSource from './reading.json';
import { chineseNumber } from './chinese-number';

type ReadingVerse = { v: number; text: string };
type ReadingChapter = { book: string; n: number; verses: ReadingVerse[] };
type ReadingData = { segments: Array<{ id: string; chapters: ReadingChapter[] }> };
type RosterName = { t: string; s: number; link?: number };
type RosterRow = {
  at: string;
  s?: number;
  label?: string;
  ls?: number;
  count?: number;
  unit?: string;
  n?: number;
  names?: RosterName[];
  quote?: { t: string; s: number };
  who?: string;
  total?: boolean;
  big?: boolean;
  bar?: boolean;
  links?: number[];
  differs?: boolean;
};
type RosterData = {
  rosters: Array<{
    segment: string;
    title: string;
    verses: string[];
    max: number;
    sections: Array<{
      title: string;
      lost?: boolean;
      bars?: boolean;
      rows: RosterRow[];
    }>;
  }>;
};

const reading = readingSource as ReadingData;
const verses = new Map<string, string>();
for (const segment of reading.segments) {
  for (const chapter of segment.chapters) {
    for (const verse of chapter.verses) {
      verses.set(chapter.book + chapter.n + ':' + verse.v, verse.text);
    }
  }
}

describe('chineseNumber', () => {
  it.each([
    ['二千一百七十二', 2172],
    ['一千零五十二', 1052],
    ['二千零五十六', 2056],
    ['一百一十二', 112],
    ['九十五', 95],
    ['十', 10],
    ['四萬二千三百六十', 42360],
    ['一萬零一十', 10010],
    ['一十八', 18],
    ['一十', 10],
    ['六萬一千', 61000],
    ['二萬', 20000],
    ['兩百', 200],
    ['零', 0],
    ['〇', 0],
  ])('converts %s', (text, expected) => {
    expect(chineseNumber(text)).toBe(expected);
  });

  it.each(['', '一百百', '二千千', '零一十', '十十', '兩兩', '一萬萬', '十二百', '三百零十', '一萬零十', '１２'])(
    'rejects %s',
    (text) => {
      expect(chineseNumber(text)).toBeNull();
    },
  );
});

const rosterModules = import.meta.glob('./roster.json', { eager: true });
const rosterModule = Object.values(rosterModules)[0] as
  | { default?: RosterData }
  | RosterData
  | undefined;
const rosterData = (rosterModule
  ? ('default' in rosterModule ? rosterModule.default : rosterModule)
  : undefined) as RosterData | undefined;

if (rosterData) {
  describe('roster.json', () => {
    it('places every label and name at its exact verse text position', () => {
      for (const roster of rosterData.rosters) {
        for (const section of roster.sections) {
          for (const row of section.rows) {
            const verse = verses.get(row.at);
            expect(verse, row.at).toBeDefined();
            if (!verse) continue;

            if (row.label !== undefined) {
              expect(row.ls, row.at + ' label position').toBeTypeOf('number');
              expect(verse.slice(row.ls!, row.ls! + row.label.length)).toBe(row.label);
            }
            for (const name of row.names ?? []) {
              expect(verse.slice(name.s, name.s + name.t.length)).toBe(name.t);
            }
          }
        }
      }
    });

    it('uses only verse-backed numbers and keeps bars within each roster maximum', () => {
      for (const roster of rosterData.rosters) {
        for (const section of roster.sections) {
          for (const row of section.rows) {
            if (row.count === undefined) continue;
            const verse = verses.get(row.at);
            expect(verse, row.at).toBeDefined();
            expect(row.n, row.at + ' number position').toBeTypeOf('number');
            if (!verse || row.n === undefined) continue;

            const numeral = verse.slice(row.n).match(/^[零〇一二三四五六七八九十百千萬兩]+/)?.[0];
            expect(numeral, row.at + ' numeral').toBeDefined();
            expect(chineseNumber(numeral ?? '')).toBe(row.count);
            if (row.bar) expect(row.count).toBeLessThanOrEqual(roster.max);
          }
        }
      }
    });
  });
} else {
  describe.skip('roster.json', () => {
    it('is generated by the site integration', () => {});
  });
}
