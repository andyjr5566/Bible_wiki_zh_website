export const STATIONS: Station[] = ROWS.map(([n, key, name, verse, q, entry, gloss, spirit]) => ({
  n, key, name, verse, q,
  ...(entry ? { entry } : {}),
  ...(gloss ? { ctGloss: gloss } : {}),
  ...(spirit ? { ctSpirit: spirit } : {}),
}));

export const station = (n: number): Station => STATIONS[n - 1];
export const stationRef = (s: Station): Ref => `民33:${s.verse}`;

/**
 * 經文裡「起行」的那個名字：第 5 站前面寫的是「從比哈希錄對面起行」，其餘等於前一站的站名。
 * 閘門用它檢查每一節的「從 X 起行」。
 */
export const departedFrom = (s: Station): string => (s.n === 5 ? '比哈希錄對面' : station(s.n - 1).name);

